"""Write a formatted Excel workbook for exploring the dataset."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

DATA = Path("data/global2000_2025.csv")
OUT = Path("output/global2000_2025.xlsx")


def main() -> None:
    df = pd.read_csv(DATA)

    ctry = (df.groupby("country")
              .agg(companies=("company", "count"),
                   revenue_musd=("revenue_musd", "sum"),
                   profits_musd=("profits_musd", "sum"),
                   assets_musd=("assets_musd", "sum"),
                   market_value_musd=("market_value_musd", "sum"),
                   employees=("employees", "sum"))
              .sort_values("revenue_musd", ascending=False).reset_index())
    ctry["revenue_share_pct"] = (ctry["revenue_musd"] / ctry["revenue_musd"].sum() * 100).round(2)

    ind = (df.groupby("industry")
             .agg(companies=("company", "count"),
                  revenue_musd=("revenue_musd", "sum"),
                  profits_musd=("profits_musd", "sum"),
                  median_margin_pct=("profit_margin_pct", "median"))
             .sort_values("revenue_musd", ascending=False).reset_index())

    notes = pd.DataFrame({"Note": [
        "Source: Forbes Global 2000, 2025 list (published June 2025).",
        "Financials are Forbes trailing-twelve-month estimates in USD millions, not audited filings.",
        "Market value is a May 2025 snapshot, not a live price.",
        "profit_margin_pct = profits / revenue; roa_pct = profits / assets; asset_turnover = revenue / assets.",
        "revenue_per_employee_usd and profit_per_employee_usd are derived from Forbes headcounts.",
        "Bank/insurer revenue is interest and fee income; comparing it to industrial revenue is misleading.",
        "Region mapping is this project's own (see scripts/build_dataset.py), not a Forbes field.",
        "Startups sheet: Forbes Cloud 100 (Sept 2025) + Next Billion-Dollar Startups (Aug 2025).",
        "Cloud 100 valuations are as of the list's publication; they are private marks, not market prices.",
        "Generated by scripts/build_dataset.py, scripts/build_startups.py and scripts/export_excel.py.",
    ]})

    with pd.ExcelWriter(OUT, engine="xlsxwriter") as xl:
        wb = xl.book
        sheets = {
            "Companies": df,
            "By Country": ctry,
            "By Industry": ind,
            "Notes": notes,
        }
        startups_path = Path("data/startups_2025.csv")
        if startups_path.exists():
            sheets["Startups"] = pd.read_csv(startups_path)

        master_path = Path("data/companies_master.csv")
        if master_path.exists():
            master = pd.read_csv(master_path)
            sheets["All sources"] = master
            outside = master[master["source"].str.startswith("Fortune")]
            if len(outside):
                sheets["Outside Forbes"] = outside.sort_values(
                    "revenue_musd", ascending=False)
        header_fmt = wb.add_format({"bold": True, "bg_color": "#0B2545", "font_color": "white",
                                    "border": 1, "text_wrap": True, "valign": "vcenter"})
        money_fmt = wb.add_format({"num_format": '$#,##0.0,"B"'})
        int_fmt = wb.add_format({"num_format": "#,##0"})
        pct_fmt = wb.add_format({"num_format": "0.0"})
        wrap_fmt = wb.add_format({"text_wrap": True, "valign": "top"})

        for name, frame in sheets.items():
            frame.to_excel(xl, sheet_name=name, index=False, startrow=0)
            ws = xl.sheets[name]
            for col_idx, col in enumerate(frame.columns):
                ws.write(0, col_idx, col, header_fmt)
                width = max(10, min(45, int(max(len(str(col)), frame[col].astype(str).str.len().max() if len(frame) else 10) * 1.1)))
                if col == "description":
                    width = 60
                ws.set_column(col_idx, col_idx, width)
                fmt = None
                if col.endswith("_musd"):
                    fmt = money_fmt
                elif col in {"employees", "rank", "year_founded"} or col.endswith("_rank"):
                    fmt = int_fmt
                elif col.endswith("_pct") or col in {"asset_turnover", "market_value_to_revenue"}:
                    fmt = pct_fmt
                if fmt is not None:
                    ws.set_column(col_idx, col_idx, width, fmt)
                if col == "description":
                    ws.set_column(col_idx, col_idx, 60, wrap_fmt)
            ws.freeze_panes(1, 2 if "company" in frame.columns else 1)
            ws.autofilter(0, 0, len(frame), len(frame.columns) - 1)

    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
