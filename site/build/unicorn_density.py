"""Build site/data/unicorn_density.js  ->  window.ATLAS.unicornDensity = {...}

Population and GDP (World Bank, latest year) for every country on the CB Insights unicorn board,
so the Startups page can show unicorns per $1 trillion of GDP and per 10 million people.
Inputs: startups/data/unicorns_cbinsights.csv, startups/data/country_pop_gdp.csv
        (the second comes from stock_market/scripts/fetch_history.py)
Run:  python site/build/unicorn_density.py
"""
import json
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'site' / 'data' / 'unicorn_density.js'

# CB Insights country name -> World Bank ISO3, only where the names differ
ISO = {'South Korea': 'KOR', 'Hong Kong': 'HKG', 'Turkey': 'TUR', 'Egypt': 'EGY', 'Czech Republic': 'CZE',
       'Slovakia': 'SVK', 'Russia': 'RUS', 'Vietnam': 'VNM', 'Iran': 'IRN', 'Venezuela': 'VEN'}
# Registered offshore for legal or tax reasons; the companies were not built there.
DOMICILE = {'Seychelles', 'Cayman Islands', 'Bermuda', 'British Virgin Islands'}


def main():
    u = pd.read_csv(ROOT / 'startups' / 'data' / 'unicorns_cbinsights.csv', encoding='utf-8-sig')
    pg = pd.read_csv(ROOT / 'startups' / 'data' / 'country_pop_gdp.csv')
    by_name = {n: r for n, r in zip(pg.country, pg.to_dict('records'))}
    by_iso = {r['iso3']: r for r in pg.to_dict('records')}
    out, missing = {}, []
    for c in sorted(u.country.dropna().unique()):
        r = by_iso.get(ISO[c]) if c in ISO else by_name.get(c)
        if r is None:
            missing.append(c); continue
        out[c] = {'iso': r['iso3'], 'pop': r['population'], 'pop_year': r['population_year'],
                  'gdp': r['gdp_usd'], 'gdp_year': None if pd.isna(r['gdp_year']) else int(r['gdp_year']),
                  'domicile': c in DOMICILE}
    if missing:
        raise SystemExit(f'No World Bank match for: {missing}. Add them to ISO.')
    OUT.write_text('/* generated by site/build/unicorn_density.py */\nwindow.ATLAS = window.ATLAS || {};\nwindow.ATLAS.unicornDensity = '
                   + json.dumps(out, separators=(',', ':')) + ';\n', encoding='utf-8')
    print('countries', len(out), 'wrote', OUT)


if __name__ == '__main__':
    main()
