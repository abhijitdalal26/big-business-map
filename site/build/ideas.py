"""Build site/data/ideas.js: a one-line "what they do" for every company that
appears in a chart on the site, keyed by a normalised company name.

assets/common.js adds the line to any chart tooltip that is about a single
company, so no page needs its own code for it.

Sources, best first:
  1. article/data/idea_overrides.csv     hand-written lines
  2. article/data/business_ideas.csv     Forbes 2000 (2025) + unlisted giants, incl. Wikipedia
  3. data/global2000_2026.csv            Forbes descriptions for the list the site uses
  4. listed_universe/data/company_profiles.csv   Wikipedia text for other listed firms

Only names that occur somewhere in site/data/*.js (except the directory, which
already shows full descriptions) are kept, so the file stays small.

Run from the repo root:  python site/build/ideas.py
"""

from __future__ import annotations

import json
import re
import sys
import unicodedata
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "article"))
from business_ideas import idea_line  # noqa: E402  (same extractor as the article)

DATA = ROOT / "site" / "data"
OUT = DATA / "ideas.js"

# Same match key as site/build/directory.py (_nk); assets/common.js has a JS copy.
_LEGAL = {'inc', 'incorporated', 'corp', 'corporation', 'co', 'company', 'ltd', 'limited', 'plc', 'nv', 'ag', 'sa', 'se',
          'spa', 'ab', 'asa', 'oyj', 'as', 'bhd', 'berhad', 'tbk', 'llc', 'lp', 'kgaa', 'gmbh', 'holding', 'holdings',
          'group', 'cos', 'companies'}


def nk(n) -> str:
    s = unicodedata.normalize('NFKD', str(n)).encode('ascii', 'ignore').decode().lower().replace('&', ' and ')
    s = re.sub(r"['’`]", '', s)
    w = re.sub(r'[^a-z0-9]+', ' ', s).split()
    j = []
    for x in w:  # glue runs of single letters: U.S. -> us
        if len(x) == 1 and j and j[-1][0] == '\0':
            j[-1] += x
        else:
            j.append('\0' + x if len(x) == 1 else x)
    w = [x.lstrip('\0') for x in j]
    w = ['corporation' if x == 'corp' else x for x in w]
    if w and w[0] in ('the', 'pt') and len(w) > 1:
        w = w[1:]
    while len(w) > 1 and w[-1] in _LEGAL:
        w = w[:-1]
    return ''.join(w)


def names_on_site() -> set[str]:
    keys = set()
    for f in DATA.glob("*.js"):
        if f.name in ("companies.js", "ideas.js"):
            continue
        for s in re.findall(r'"((?:[^"\\]|\\.)*)"', f.read_text(encoding="utf-8")):
            if 2 <= len(s) < 90:
                try:
                    keys.add(nk(json.loads(f'"{s}"')))
                except json.JSONDecodeError:
                    pass
    keys.discard("")
    return keys


def good(line) -> bool:
    return (isinstance(line, str) and len(line) >= 25
            and not re.search(r"\blist of\b|^This (?:is|list|article)\b|\brefers? to\b|\bmay (?:also )?refer\b|\bdefunct\b|\bliquidation\b|\bbankrupt|^Was\b", line, re.I))


def main() -> None:
    wanted = names_on_site()
    # Map and country charts label regions by ISO code or name; never let those match a company.
    cm = pd.read_csv(ROOT / "data/country_meta.csv", encoding="utf-8-sig")
    wanted -= {nk(x) for x in pd.concat([cm.iso3, cm.name]).dropna()}
    # Fund acronyms collide with companies (KIA = Kuwait Investment Authority, not Kia Motors).
    funds = pd.read_csv(ROOT / "site/build/context_data/sovereign_and_pension_funds_globalswf.csv")
    wanted -= {nk(x) for x in funds.name.dropna()}
    ideas: dict[str, str] = {}

    def add(name, line):
        k = nk(name)
        if k and k in wanted and k not in ideas and good(line):
            ideas[k] = line.strip()

    ov = pd.read_csv(ROOT / "article/data/idea_overrides.csv", keep_default_na=False)
    for r in ov.itertuples():
        add(r.company, r.what_they_do)
    art = pd.read_csv(ROOT / "article/data/business_ideas.csv")
    for r in art.itertuples():
        add(r.company, r.what_they_do)
    g26 = pd.read_csv(ROOT / "data/global2000_2026.csv", encoding="utf-8-sig")
    for r in g26.itertuples():
        add(r.company, idea_line(r.description))
    prof = pd.read_csv(ROOT / "listed_universe/data/company_profiles.csv")
    for r in prof.itertuples():
        add(r.company, idea_line(r.description))

    js = ("/* generated by site/build/ideas.py: one-line 'what they do' per company, "
          "keyed by normalised name */\nwindow.ATLAS_IDEAS = "
          + json.dumps(ideas, ensure_ascii=False, separators=(",", ":"), sort_keys=True) + ";\n")
    OUT.write_text(js, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(ideas):,} companies "
          f"({len(wanted):,} names on the site), {OUT.stat().st_size / 1024:,.0f} KB")


if __name__ == "__main__":
    main()
