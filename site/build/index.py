"""Build site/data/index.js (window.ATLAS.index) for the overview hub.
Run: python site/build/index.py
"""
import json, os, re
import pandas as pd
import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
D = os.path.join(ROOT, 'data')
OUTD = os.path.join(ROOT, 'data_analysis', 'output')
OUT = os.path.join(ROOT, 'site', 'data', 'index.js')

def rd(p):
    return pd.read_csv(p, encoding='utf-8-sig')

M = json.load(open(os.path.join(OUTD, 'metrics.json'), encoding='utf-8'))
macro = rd(os.path.join(D, 'world_macro.csv'))
def mac(ind, yr=2024):
    s = macro[(macro.indicator == ind) & (macro.year == yr)]['value']
    return float(s.iloc[0]) if len(s) else None

g = rd(os.path.join(D, 'global2000_2026.csv'))
uni = rd(os.path.join(ROOT, 'startups', 'data', 'unicorns_cbinsights.csv'))
ex = rd(os.path.join(ROOT, 'stock_market', 'data', 'exchanges.csv'))
lu = rd(os.path.join(ROOT, 'listed_universe', 'data', 'listed_universe.csv'))

PRETTY = {'United States': 'United States'}
companies = []
for _, r in g.iterrows():
    companies.append([r.company, r.country, r.sector, r.industry_canon,
                      None if pd.isna(r.revenue_musd) else round(float(r.revenue_musd), 0),
                      None if pd.isna(r.profits_musd) else round(float(r.profits_musd), 0),
                      None if pd.isna(r.market_value_musd) else round(float(r.market_value_musd), 0),
                      None if pd.isna(r.employees) else int(r.employees), int(r['rank'])])

def conc(col):
    v = g[col].clip(lower=0).sort_values(ascending=False).values
    tot = v.sum()
    cum = np.cumsum(v) / tot
    marks = {n: float(cum[n - 1]) for n in (10, 20, 50, 100, 200, 500, 1000, 2000)}
    half = int(np.searchsorted(cum, 0.5) + 1)
    # thin the curve to keep the file small: every rank to 200, then every 5th
    pts = [[i + 1, round(float(cum[i]) * 100, 2)] for i in range(len(cum)) if i < 200 or (i + 1) % 5 == 0]
    return dict(marks=marks, half=half, curve=pts)
concentration = {'revenue': conc('revenue_musd'), 'profit': conc('profits_musd'), 'mv': conc('market_value_musd')}

sm = M['scale']['metrics']
tiles = dict(
    world_gdp=mac('NY.GDP.MKTP.CD'), listed_domestic=mac('CM.MKT.LDOM.NO'), labor_force=mac('SL.TLF.TOTL.IN'),
    population=mac('SP.POP.TOTL'),
    g_rev=sm['forbes_revenue_total'], g_prof=sm['forbes_profit_total'], g_mv=sm['forbes_market_cap_total'],
    g_emp=sm['forbes_employees_total'], g_assets=sm['forbes_assets_total'], g_margin=sm['forbes_blended_margin'],
    g_loss=sm['forbes_loss_makers'],
    unicorns=int(len(uni)), unicorn_val=float(uni.valuation_busd.sum() * 1e9),
    universe=M['companies']['metrics']['companies'], universe_rows=17985,
    exchanges=int(len(ex)), exchange_mcap=float(ex.total_market_cap_usd.sum()), exchange_cos=int(ex.companies.sum()),
    listed_universe=int(len(lu)), listed_mcap=float(lu.market_cap_usd.sum()),
    countries_g2k=int(g.country.nunique()), fortune_outside=90, fortune_outside_rev=6.4e12,
)

# dataset registry: parse Appendix A of STUDY_PACK.md
sp = open(os.path.join(OUTD, 'STUDY_PACK.md'), encoding='utf-8').read()
sec = sp.split('# Appendix A')[1].split('# Appendix B')[0]
registry = []
for line in sec.splitlines():
    if line.startswith('|') and not line.startswith('|---') and 'Dataset | Kind' not in line:
        cells = [c.strip() for c in line.strip('|').split('|')]
        if len(cells) == 6:
            registry.append(dict(zip(['dataset', 'kind', 'trust', 'publisher', 'file', 'notes'], cells)))
caveats = []
cav = sp.split('# Appendix D: caveats')[1]
for m_ in re.finditer(r"\{'topic': ['\"](.+?)['\"], 'detail': ['\"](.+?)['\"]\}", cav):
    caveats.append(dict(topic=m_.group(1), detail=m_.group(2)))
vint = rd(os.path.join(OUTD, 'data', 'data_quality__data_vintages.csv')).to_dict('records')

data = dict(tiles=tiles, companies=companies,
            company_cols=['company', 'country', 'sector', 'industry', 'rev_musd', 'prof_musd', 'mv_musd', 'emp', 'rank'],
            concentration=concentration, registry=registry, caveats=caveats, vintages=vint,
            gdp_series=macro[macro.indicator == 'NY.GDP.MKTP.CD'][['year', 'value']].values.tolist())

def cj(o):
    if isinstance(o, float): return None if (np.isnan(o) or np.isinf(o)) else o
    if isinstance(o, dict): return {str(k): cj(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)): return [cj(v) for v in o]
    if isinstance(o, np.integer): return int(o)
    if isinstance(o, np.floating): return cj(float(o))
    return o

with open(OUT, 'w', encoding='utf-8') as fh:
    fh.write('/* generated by site/build/index.py */\nwindow.ATLAS = window.ATLAS || {};\nwindow.ATLAS.index = ')
    fh.write(json.dumps(cj(data), ensure_ascii=False, separators=(',', ':')))
    fh.write(';\n')
print(json.dumps(cj(tiles), indent=0))
print({k: (v['marks'], v['half']) for k, v in concentration.items()})
print(len(registry), 'registry rows', len(caveats), 'caveats', os.path.getsize(OUT) // 1024, 'KB')
